// Return all catalog games, enriching playable games with live engine configs
export const GAME_LIST: GameDefinition[] = MASTER_CATALOG.map(item => {
  const engine = GAME_REGISTRY[item.id];
  if (engine) {
    return {
      ...item,
      ...engine.config,
      status: 'playable',
    };
  }
  return item;
});

export function getGameEngine(gameId: string): GameEngine | undefined {
  return GAME_REGISTRY[gameId] || (gameId === 'reactionrace' ? GAME_REGISTRY.reactionrush : undefined);
}

export function getGameDefinition(gameId: string): GameDefinition | undefined {
  return GAME_LIST.find(g => g.id === gameId || (gameId === 'reactionrace' && g.id === 'reactionrush'));
}
